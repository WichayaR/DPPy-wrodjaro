#!/usr/bin/env python3

first_number = int(input("Enter the first number: ").strip())
second_number = int(input("Enter the second number: ").strip())

print("Thank you!")
print(f"{first_number} + {second_number} = {first_number + second_number}")
print(f"{first_number} - {second_number} = {first_number - second_number}")
print(f"{first_number} / {second_number} = {first_number / second_number}")
print(f"{first_number} * {second_number} = {first_number * second_number}")


